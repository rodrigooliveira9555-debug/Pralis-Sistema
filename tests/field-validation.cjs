assert.equal(r.cpfValid('529.982.247-25'),true);
assert.equal(r.cpfValid('529.982.247-24'),false);
for(const v of ['2024-02-29','2000-02-29','0001-01-01','9999-12-31'])assert.equal(r.dateValid(v),true,v);
