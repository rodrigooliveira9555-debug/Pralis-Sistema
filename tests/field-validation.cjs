const assert=require('node:assert/strict');
const r=require('../dist/field-validation.js');
for(const [a,b] of [['1','R$ 0,01'],['1234','R$ 12,34'],['123456','R$ 1.234,56'],['',''],['0','R$ 0,00'],['R$ 12,34','R$ 12,34']])assert.equal(r.moneyMask(a),b);
